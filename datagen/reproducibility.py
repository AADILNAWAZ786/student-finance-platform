"""verify_reproducibility (Phase 8, P8-D4): generate and export the same seed twice, in two
isolated processes with their own fresh SQLite databases, and compare the deterministic files.

Each run gets its own directory under the work directory::

    run_a/settings/sf_repro_run_a.py   settings module: config.settings + its own DB paths
    run_a/db/{default,ground_truth}.sqlite3
    run_a/export/                      export_data output
    run_a/logs/<step>.log              stdout + stderr of every step

The runs are sequential (never in parallel: memory, and SQLite). Before anything is written, each
run's settings are loaded in a subprocess and every database path must lie inside its own run
directory and must not exist yet; the owner's databases can therefore never be opened.

Compared: the set of checksummed files and each file's sha256, and dataset_manifest.json byte for
byte (it holds no timestamps). run_log.json is excluded: it records times, hosts and durations.
A mismatch names the first differing file and, for a table, the first differing primary key,
column and both values. The report is written to <workdir>/reproducibility_report.md.
"""

from __future__ import annotations

import csv
import json
import os
import platform
from datagen.platform_metrics import run_monitored
import shutil
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path

from datagen import provenance

REPO = Path(__file__).resolve().parent.parent
EXCLUDED = ("run_log.json",)  # execution metadata: never compared
RUNS = ("run_a", "run_b")
HASH_SEEDS = {"run_a": "1", "run_b": "2"}
csv.field_size_limit(sys.maxsize)


class ReproducibilityError(Exception):
    """The check could not be carried out (as opposed to: it ran and found a difference)."""


@dataclass
class RunInfo:
    name: str
    root: Path
    steps: dict[str, float] = field(default_factory=dict)
    combined_sha256: str | None = None
    files: int = 0
    rows: int = 0
    peak_rss_mb: float = 0.0


@dataclass
class Outcome:
    workdir: Path
    report_path: Path
    identical: bool
    runs: list[RunInfo]
    differences: list[str]
    compared_files: int
    peak_rss_mb: float


# --- one isolated run ---------------------------------------------------------------------------


def _settings_module(run: RunInfo) -> str:
    name = f"sf_repro_{run.name}"
    settings_dir = run.root / "settings"
    settings_dir.mkdir(parents=True)
    db = run.root / "db"
    db.mkdir()
    (settings_dir / f"{name}.py").write_text(
        "# generated by verify_reproducibility: an isolated run with its own databases\n"
        "from config.settings import *  # noqa: F403\n"
        "from config.settings import DATABASES\n\n"
        f'DATABASES["default"]["NAME"] = {str(db / "default.sqlite3")!r}\n'
        f'DATABASES["ground_truth"]["NAME"] = {str(db / "ground_truth.sqlite3")!r}\n',
        encoding="utf-8",
    )
    return name


def _env(run: RunInfo, module: str) -> dict[str, str]:
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join([str(REPO), str(run.root / "settings")])
    env["DJANGO_SETTINGS_MODULE"] = module
    # deliberately different string-hash seeds, so output that depends on set or dict-of-str
    # iteration order shows up as a difference instead of passing by luck
    env["PYTHONHASHSEED"] = HASH_SEEDS[run.name]
    return env


def _step(run: RunInfo, label: str, argv: list[str], env: dict[str, str]) -> str:
    logs = run.root / "logs"
    logs.mkdir(exist_ok=True)
    t0 = time.monotonic()
    proc, peak_mb = run_monitored([sys.executable, *argv], cwd=REPO, env=env)
    run.peak_rss_mb = max(run.peak_rss_mb, peak_mb)
    run.steps[label] = round(time.monotonic() - t0, 2)
    (logs / f"{label}.log").write_text(
        f"$ {' '.join(argv)}\n--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}",
        encoding="utf-8",
    )
    if proc.returncode != 0:
        tail = (proc.stderr or proc.stdout).strip().splitlines()[-5:]
        raise ReproducibilityError(
            f"{run.name}: step {label!r} failed (exit {proc.returncode}); "
            f"see {logs / (label + '.log')}:\n  " + "\n  ".join(tail)
        )
    return proc.stdout


SAFETY_PROBE = (
    "import json, django; django.setup(); from django.conf import settings; "
    "print(json.dumps({a: str(d['NAME']) for a, d in settings.DATABASES.items()}))"
)


def _check_isolated(run: RunInfo, env: dict[str, str]) -> None:
    names = json.loads(_step(run, "settings_probe", ["-c", SAFETY_PROBE], env).strip())
    if set(names) != {"default", "ground_truth"}:
        raise ReproducibilityError(f"{run.name}: unexpected database aliases {sorted(names)}")
    for alias, name in names.items():
        path = Path(name).resolve()
        if run.root.resolve() not in path.parents:
            raise ReproducibilityError(
                f"{run.name}: database {alias} resolves to {path}, outside {run.root}; refusing"
            )
        if path.exists():
            raise ReproducibilityError(f"{run.name}: database {path} already exists; refusing")


def _one_run(run: RunInfo, args: list[str], config: str | None) -> None:
    module = _settings_module(run)
    env = _env(run, module)
    _check_isolated(run, env)
    manage = str(REPO / "manage.py")
    for alias in ("default", "ground_truth"):
        _step(run, f"migrate_{alias}", [manage, "migrate", "--database", alias, "-v", "0"], env)
    cfg = ["--config", config] if config else []
    _step(run, "generate_data", [manage, "generate_data", *args, *cfg], env)
    out = run.root / "export"
    _step(run, "export_data", [manage, "export_data", "--out", str(out), *cfg], env)
    manifest = json.loads((out / "dataset_manifest.json").read_text(encoding="utf-8"))
    run.combined_sha256 = manifest["combined_sha256"]
    run.files = len(manifest["files"])
    run.rows = sum(manifest["row_counts"].values())


# --- comparison ---------------------------------------------------------------------------------


def deterministic_files(export_dir: Path) -> dict[str, str]:
    """Relative path -> sha256 of every compared file (all but run_log.json)."""
    from datagen.verification import _sha256

    return {
        p.relative_to(export_dir).as_posix(): _sha256(p)
        for p in sorted(export_dir.rglob("*"))
        if p.is_file() and p.name not in EXCLUDED
    }


def _first_row_difference(a: Path, b: Path) -> str:
    with open(a, encoding="utf-8", newline="") as fa, open(b, encoding="utf-8", newline="") as fb:
        ra, rb = csv.reader(fa), csv.reader(fb)
        ha, hb = next(ra, []), next(rb, [])
        if ha != hb:
            return f"headers differ: {ha} vs {hb}"
        for n, (x, y) in enumerate(zip(ra, rb, strict=False), 1):
            if x != y:
                if x[:1] != y[:1]:
                    return f"row {n}: primary key {x[:1]} in run_a, {y[:1]} in run_b"
                for col, va, vb in zip(ha, x, y, strict=False):
                    if va != vb:
                        return f"primary key {x[0]}, column {col}: {va!r} in run_a, {vb!r} in run_b"
        rest_a, rest_b = sum(1 for _ in ra), sum(1 for _ in rb)
        if rest_a or rest_b:
            return f"row counts differ: run_a has {rest_a} extra rows, run_b {rest_b}"
    return "rows equal; bytes differ (encoding or line endings)"


def _first_line_difference(a: Path, b: Path) -> str:
    with (
        open(a, encoding="utf-8", errors="replace") as fa,
        open(b, encoding="utf-8", errors="replace") as fb,
    ):
        for n, (x, y) in enumerate(zip(fa, fb, strict=False), 1):
            if x != y:
                return f"line {n}: {x.rstrip()[:160]!r} in run_a, {y.rstrip()[:160]!r} in run_b"
    return "one file is a prefix of the other (lengths differ)"


def compare(a: Path, b: Path) -> tuple[list[str], int]:
    """Differences between two export directories (empty when reproducible), and the number of
    files compared."""
    fa, fb = deterministic_files(a), deterministic_files(b)
    diffs = [f"only in run_a: {rel}" for rel in sorted(set(fa) - set(fb))]
    diffs += [f"only in run_b: {rel}" for rel in sorted(set(fb) - set(fa))]
    for rel in sorted(set(fa) & set(fb)):
        if fa[rel] == fb[rel]:
            continue
        if rel.endswith(".csv"):
            table = Path(rel).stem
            detail = _first_row_difference(a / rel, b / rel)
            diffs.append(f"{rel} differs (table {table}): {detail}")
        else:
            diffs.append(f"{rel} differs: {_first_line_difference(a / rel, b / rel)}")
    return diffs, len(set(fa) | set(fb))


# --- report and entry point ---------------------------------------------------------------------


def _report(outcome: Outcome, params: dict) -> str:
    env = provenance.environment()
    status = "REPRODUCIBLE" if outcome.identical else "NOT REPRODUCIBLE"
    lines = [
        "# Reproducibility report",
        "",
        f"Result: **{status}**",
        "",
        "## Parameters",
        "",
        *[f"- {k}: `{v}`" for k, v in params.items()],
        f"- git_sha: `{env.get('git_sha')}`",
        f"- python: `{platform.python_version()}`, django: `{env.get('django')}`, "
        f"sqlite: `{env.get('sqlite')}`",
        f"- work directory: `{outcome.workdir}`",
        "",
        "## Runs (sequential, isolated databases)",
        "",
        "| run | PYTHONHASHSEED | combined_sha256 | files | dataset rows | migrate s "
        "| generate s | export s |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in outcome.runs:
        migrate = round(
            r.steps.get("migrate_default", 0) + r.steps.get("migrate_ground_truth", 0), 2
        )
        lines.append(
            f"| {r.name} | {HASH_SEEDS[r.name]} | `{r.combined_sha256}` | {r.files} "
            f"| {r.rows} | {migrate} | {r.steps.get('generate_data')} "
            f"| {r.steps.get('export_data')} |"
        )
    lines += [
        "",
        f"Peak RSS of a child process: {outcome.peak_rss_mb:.0f} MB.",
        "",
        "## Comparison",
        "",
        f"{outcome.compared_files} files compared by sha256 (dataset CSV/JSON/SQL, ground truth, "
        "reports, both manifests). Excluded: `run_log.json` (execution times and host).",
        "",
    ]
    if outcome.identical:
        lines.append("All compared files are byte-identical.")
    else:
        lines.append(f"{len(outcome.differences)} difference(s):")
        lines.append("")
        lines += [f"- {d}" for d in outcome.differences]
        lines += [
            "",
            "Both run directories were kept for inspection (databases, exports, step logs).",
        ]
    return "\n".join(lines) + "\n"


def reproduce(
    *,
    seed: int,
    scale: str | None = None,
    scale_factor: str | None = None,
    config: str | None = None,
    workdir: str | os.PathLike | None = None,
    keep: bool = False,
) -> Outcome:
    if workdir is None:
        root = Path(tempfile.mkdtemp(prefix="sf-repro-"))
    else:
        root = Path(workdir).resolve()
        if root.exists() and any(root.iterdir()):
            raise ReproducibilityError(f"{root} is not empty; choose a new --workdir")
        root.mkdir(parents=True, exist_ok=True)
    if config:
        config = str(Path(config).resolve())
        if not Path(config).is_file():
            raise ReproducibilityError(f"config file {config} does not exist")
    args = ["--seed", str(seed)]
    if scale_factor is not None:
        args += ["--scale-factor", str(scale_factor)]
    else:
        args += ["--scale", scale or "starter"]
    params = {
        "seed": seed,
        "scale": scale_factor and f"factor {scale_factor}" or (scale or "starter"),
        "config": config or "default (config/generation.yaml)",
    }

    runs = [RunInfo(name, root / name) for name in RUNS]
    for run in runs:  # sequential by design
        run.root.mkdir()
        _one_run(run, args, config)
    diffs, compared = compare(runs[0].root / "export", runs[1].root / "export")
    peak = max((r.peak_rss_mb for r in runs), default=0.0)
    outcome = Outcome(
        workdir=root,
        report_path=root / "reproducibility_report.md",
        identical=not diffs,
        runs=runs,
        differences=diffs,
        compared_files=compared,
        peak_rss_mb=peak,
    )
    outcome.report_path.write_text(_report(outcome, params), encoding="utf-8")
    if outcome.identical and not keep:
        for run in runs:
            shutil.rmtree(run.root)
    return outcome
