def _code(call) -> str:
    body = call["response"]["body"]
    if isinstance(body, dict) and isinstance(body.get("error"), dict):
        return f"{body['error'].get('code')} ({body['error'].get('rule_id') or '-'})"
    return ""


def render_report(res: dict, transcript: list) -> str:
    p = res["parameters"]
    lines = [
        "# Student finance demo workflow",
        "",
        f"Seed `{p['seed']}`, scale `{p['scale']}`, config `{p['config']}`, business date "
        f"{p['business_date']}. Isolated temporary databases; this file depends only on seed, "
        "config and code (execution times are in the last section).",
        "",
        "| stage | result |",
        "|---|---|",
        *[f"| {s} | {res['stages'][s]} |" for s in STAGES],
        "",
    ]
    if res.get("error"):
        lines += ["**Failed:** " + res["error"], ""]
    a, b = res.get("A_dataset"), res.get("B_export")
    if a:
        lines += [
            "## A. Dataset",
            "",
            f"Generation run {a['generation_run']}, reconciliation run {a['reconciliation_run']}, "
            f"dataset checksum `{a['dataset_checksum']}`.",
            "",
            "| table | rows |",
            "|---|---|",
            *[f"| {t} | {n} |" for t, n in sorted(a["row_counts"].items())],
            "",
        ]
    if b:
        lines += [
            "## B. Export (`export/`)",
            "",
            f"{b['files']} checksummed files, {b['dataset_rows']} dataset rows, "
            f"{b['ground_truth_rows']} ground-truth labels (in `export/ground_truth/`, apart from "
            f"`export/dataset/`), {b['findings_rows']} findings. combined_sha256 "
            f"`{b['combined_sha256']}`.",
            "",
            "verify_export: "
            + ", ".join(f"{k} {'PASS' if v else 'FAIL'}" for k, v in b["verify_export"].items()),
            "",
        ]
    d = res.get("C_anomalies")
    if d:
        lines += [
            "## C. Anomalies (generation's reconciliation run)",
            "",
            f"{d['reconciliation_run']}: {d['findings_count']} findings; {d['labels']} labels.",
            "",
            "| issue type | labels | findings | example finding | record | label "
            "| expected decision |",
            "|---|---|---|---|---|---|---|",
            *[
                f"| {t} | {v['labels']} | {v['findings']} | {v['example_finding']} | "
                f"{v['example_record']} | {v['example_label']} | {v['expected_decision']} |"
                for t, v in d["by_type"].items()
            ],
            "",
        ]
    e = res.get("D_evaluation")
    if e:
        lines += [
            "## D. Evaluation",
            "",
            "| issue type | TP | FP | FN | precision | recall | F1 |",
            "|---|---|---|---|---|---|---|",
        ]
        for t, v in e["by_type"].items():
            lines.append(
                f"| {t} | {v.get('tp')} | {v.get('fp')} | {v.get('fn')} | {v.get('precision')} | "
                f"{v.get('recall')} | {v.get('f1')} |"
            )
        lines += [
            "",
            f"Overall: `{json.dumps(e['overall'], sort_keys=True)}`. Consequential findings: "
            f"{e['consequential']}; unexpected: {e['unexpected']}. Students: "
            f"`{json.dumps(e['students'], sort_keys=True)}`. Meets targets: {e['meets_targets']}.",
            "",
        ]
    c = res.get("E_api")
    if c:
        lines += ["## E. API workflow", ""]
        lines += [f"- {k}: `{v}`" for k, v in c.items()]
        lines += [
            "",
            "| # | stage | call | status | error code |",
            "|---|---|---|---|---|",
            *[
                f"| {x['n']} | {x['stage']} | {x['title']}: `{x['request']['method']} "
                f"{x['request']['path']}` | {x['response']['status']} | {_code(x)} |"
                for x in transcript
            ],
            "",
        ]
    f = res.get("F_reference")
    if f:
        lines += ["## F. Every other API operation", ""]
        lines += [f"- {k}: `{v}`" for k, v in f.items()] + [""]
    g = res.get("G_permissions")
    if g:
        lines += [
            "## G. Permissions (measured)",
            "",
            "| operation | allowed |",
            "|---|---|",
            *[f"| `{op}` | {', '.join(v['allowed'])} |" for op, v in g.items()],
            "",
        ]
    lines += [
        "## Files",
        "",
        "- `api_transcript.json`: every request and response (no headers, tokens or cookies; "
        f"only {', '.join(sorted(VOLATILE_KEYS))} masked as `{VOLATILE}`)",
        "- `demo_results.json`: the figures above, machine-readable",
        "- `export/`: the Phase 8 export (`dataset/`, `ground_truth/`, `reports/`, manifests)",
        "- `logs/generate_data.log`: the generator's own output; `logs/timings.json`: stage times",
    ]
    return "\n".join(lines) + "\n"
