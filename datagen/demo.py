"""demo_workflow (Phase 9, P9-D1…D4): the complete student-finance workflow, end to end, in
isolated temporary SQLite databases.

Two processes:

* **parent** (``run_demo``): refuses a non-empty ``--out``; writes ``<out>/run/settings/`` (a
  settings module whose two databases live in ``<out>/run/db/`` and which carries the
  ``SF_DEMO_ISOLATED`` marker); probes it in a subprocess (every database path inside the run
  directory and not yet existing, as ``verify_reproducibility`` does) and only then starts
* **child** (``demo_workflow --child``, same settings module): ``assert_isolated`` refuses
  unless the marker is set, every configured database lies inside the run directory and none
  of them existed before; then it runs the stages below.

The configured (owner's) databases are never opened by either process: the parent does not
touch any database, and the child's settings name only the run directory's files.

Stages (each checked; the first failure stops the demo with a non-zero exit):

  A dataset    migrate, generate_data (stages 1–17, injection, DATAGEN reconciliation run)
  B export     export_data (CSV / JSON / SQL, ground truth apart, manifests) + verify_export
  C anomalies  the generation's reconciliation findings, one labelled example per required
               type (label read from the exported ground_truth.json), through the API
  D evaluation TP / FP / FN, precision, recall, F1 and reconciliation coverage (the API)
  E api        the ARCHITECTURE §9.3 scenario and the exception paths, through the real API
               (URLs, token authentication, permissions, serializers, services), on top of the
               generated dataset; every request and response captured

  F reference  every other operation of the API once (master-data writes, fee versions,
               status changes, void, reject, refresh, an ALL-scope reconciliation run, every
               list and detail read), so all 64 operations are exercised and captured
  G permissions every operation called as each role and anonymously with an empty body and
               unknown IDs (refused before validation, so nothing is written): the measured
               role table API.md publishes

C and D run before E adds students: the evaluation counts the students in the database, so it
must see exactly the generated dataset (P9-O3).

Outputs in ``<out>``: ``demo_report.md``, ``api_transcript.json`` (no headers, tokens or
cookies), ``demo_results.json``, ``export/`` (Phase 8 layout), ``logs/``.
"""

