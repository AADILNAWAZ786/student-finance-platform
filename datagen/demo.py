class DemoError(Exception):
    """The demo cannot run, or a required stage failed."""


# --- parent -------------------------------------------------------------------------------------


def _write_settings(run_root: Path, base_settings: str) -> str:
    settings_dir = run_root / "settings"
    settings_dir.mkdir(parents=True)
    (run_root / "db").mkdir()
    db = run_root / "db"
    (settings_dir / f"{SETTINGS_NAME}.py").write_text(
        "# generated by demo_workflow: isolated demo databases (never the configured ones)\n"
        f"from {base_settings} import *  # noqa: F403\n"
        f"from {base_settings} import DATABASES\n\n"
        f'DATABASES["default"]["NAME"] = {str(db / "default.sqlite3")!r}\n'
        f'DATABASES["ground_truth"]["NAME"] = {str(db / "ground_truth.sqlite3")!r}\n'
        f"{MARKER} = True\n"
        f"SF_DEMO_RUN_DIR = {str(run_root)!r}\n",
        encoding="utf-8",
    )
    return SETTINGS_NAME


def run_demo(
    *,
    out,
    seed: int,
    scale: str | None = None,
    scale_factor: str | None = None,
    config: str | None = None,
    keep: bool = False,
    base_settings: str = "config.settings",
    extra_pythonpath: tuple[str, ...] = (),
    stream=None,
) -> dict:
    out = Path(out).resolve()
    if out.exists() and (not out.is_dir() or any(out.iterdir())):
        raise DemoError(f"{out} already exists and is not an empty directory; choose a new --out")
    if config:
        config = str(Path(config).resolve())
        if not Path(config).is_file():
            raise DemoError(f"config file {config} does not exist")
    out.mkdir(parents=True, exist_ok=True)
    run = rp.RunInfo("demo", out / "run")
    run.root.mkdir()
    module = _write_settings(run.root, base_settings)
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join([str(REPO), str(run.root / "settings"), *extra_pythonpath])
    env["DJANGO_SETTINGS_MODULE"] = module
    env["PYTHONHASHSEED"] = "0"
    rp._check_isolated(run, env)  # refuses before anything is migrated or written

    argv = [sys.executable, str(REPO / "manage.py"), "demo_workflow", "--child", "--out", str(out)]
    argv += ["--seed", str(seed)]
    argv += (
        ["--scale-factor", str(scale_factor)] if scale_factor else ["--scale", scale or "starter"]
    )
    if config:
        argv += ["--config", config]
    import subprocess

    t0 = time.monotonic()
    proc = subprocess.Popen(  # noqa: S603 - our own manage.py with our own arguments
        argv, cwd=REPO, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True
    )
    lines = []
    for line in proc.stdout:
        lines.append(line)
        if stream is not None:
            stream.write(line)
    proc.wait()
    seconds = round(time.monotonic() - t0, 1)
    (run.root / "child.log").write_text("".join(lines), encoding="utf-8")
    import resource

    peak_mb = round(resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss / 1024)
    results_path = out / "demo_results.json"
    results = json.loads(results_path.read_text()) if results_path.is_file() else {}
    timings_path = out / "logs/timings.json"
    timings = json.loads(timings_path.read_text()) if timings_path.is_file() else {}
    results["runtime_seconds"] = seconds
    results["timings"] = timings
    results["peak_rss_mb"] = peak_mb
    results["exit_code"] = proc.returncode
    report = out / "demo_report.md"
    if report.is_file():  # execution metadata goes after the deterministic body
        with open(report, "a", encoding="utf-8") as fh:
            fh.write(
                f"\n## Execution (not deterministic)\n\nRuntime {seconds} s (stages: "
                f"{json.dumps(timings, sort_keys=True)}), peak memory of the demo process "
                f"{peak_mb} MB, exit code {proc.returncode}.\n"
            )
    if proc.returncode != 0:
        tail = "".join(lines[-15:])
        raise DemoError(
            f"demo_workflow failed (exit {proc.returncode}); the databases and logs are kept in "
            f"{run.root}.\n{tail}"
        )
    if not keep:
        shutil.rmtree(run.root / "db")
    results["kept_databases"] = keep
    return results


# --- child: the isolation guard -----------------------------------------------------------------


def assert_isolated() -> Path:
    """Refuse unless this process runs on the demo's own, new databases."""
    from django.conf import settings
    from django.db import connections

    if getattr(settings, MARKER, False) is not True:
        raise DemoError(
            "refusing to run: the settings are not demo_workflow's isolated settings "
            f"({MARKER} is not set). Run `python manage.py demo_workflow` (without --child)."
        )
    root = Path(settings.SF_DEMO_RUN_DIR).resolve()
    if set(connections.databases) != {"default", "ground_truth"}:
        raise DemoError(f"refusing to run: unexpected databases {sorted(connections.databases)}")
    for alias in ("default", "ground_truth"):
        path = Path(str(connections.databases[alias]["NAME"])).resolve()
        if root not in path.parents:
            raise DemoError(f"refusing to run: database {alias} is {path}, outside {root}")
        if path.exists():
            raise DemoError(f"refusing to run: database {path} already exists (not new)")
    return root


# --- child: API transcript ----------------------------------------------------------------------


def mask(value):
    if isinstance(value, dict):
        return {k: (VOLATILE if k in VOLATILE_KEYS else mask(v)) for k, v in value.items()}
    if isinstance(value, list):
        return [mask(v) for v in value]
    return value


class StageFailed(DemoError):
    pass


@dataclass
class Api:
    client: object
    stage: str = ""
    calls: list = field(default_factory=list)

    def call(self, title, method, path, body=None, *, params=None, expect=200, code=None):
        """One request; records it; checks the status (and the error code, for a refusal)."""
        fn = getattr(self.client, method.lower())
        if method == "GET":
            r = fn(path, params or {})
        else:
            r = fn(path, body if body is not None else {}, format="json")
        data = r.json() if r.content else None
        self.calls.append(
            {
                "n": len(self.calls) + 1,
                "stage": self.stage,
                "title": title,
                "request": {"method": method, "path": path, "query": params, "body": body},
                "response": {"status": r.status_code, "body": mask(data)},
                "expected_status": expect,
            }
        )
        if r.status_code != expect:
            raise StageFailed(
                f"{title}: {method} {path} returned {r.status_code}, expected {expect}: {data}"
            )
        if code and (data or {}).get("error", {}).get("code") != code:
            raise StageFailed(f"{title}: expected error code {code}, got {data}")
        return data


def _money(x) -> Decimal:
    return Decimal(str(x))


# --- child: stages ------------------------------------------------------------------------------


@dataclass
class Child:
    out: Path
    seed: int
    scale: str | None
    scale_factor: str | None
    config: str | None
    log: object
    results: dict = field(default_factory=dict)
    ctx: dict = field(default_factory=dict)  # IDs created by stage E, reused by stage F
    timings: dict = field(default_factory=dict)  # execution metadata: never in the results

    def say(self, text=""):
        self.log.write(text + "\n")
        self.log.flush()

    # A ---------------------------------------------------------------------------------------
    def stage_dataset(self):
        import io

        from django.core.management import call_command

        from datagen.models import GenerationRun
        from reconciliation.models import ReconciliationRun

        for alias in ("default", "ground_truth"):
            call_command("migrate", database=alias, verbosity=0)
        args = ["--seed", str(self.seed)]
        args += (
            ["--scale-factor", self.scale_factor]
            if self.scale_factor
            else ["--scale", self.scale or "starter"]
        )
        if self.config:
            args += ["--config", self.config]
        buf = io.StringIO()
        t0 = time.monotonic()
        call_command("generate_data", *args, stdout=buf)
        (self.out / "logs").mkdir(exist_ok=True)
        (self.out / "logs/generate_data.log").write_text(buf.getvalue(), encoding="utf-8")
        gen = GenerationRun.objects.get()
        recon = ReconciliationRun.objects.get(triggered_by="DATAGEN")
        self.results["A_dataset"] = {
            "generation_run": gen.pk,
            "reconciliation_run": recon.pk,
            "seed": gen.seed,
            "scale_name": gen.scale_name,
            "scale_factor": str(gen.scale_factor),
            "config_hash": gen.config_hash,
            "row_counts": gen.row_counts,
            "dataset_checksum": gen.checksums["dataset"],
        }
        self.timings["generate_seconds"] = round(time.monotonic() - t0, 1)
        self.say(
            f"  generated {gen.pk}: seed {gen.seed}, {gen.scale_name}, "
            f"{sum(gen.row_counts.values())} rows, reconciled by {recon.pk}"
        )

    # B ---------------------------------------------------------------------------------------
    def stage_export(self):
        from datagen import export as ex
        from datagen import verification as vf

        t0 = time.monotonic()
        result = ex.export(self.out / "export", config_path=self.config)
        report = vf.verify(self.out / "export")
        m = result.manifest
        self.results["B_export"] = {
            "combined_sha256": m["combined_sha256"],
            "files": len(m["files"]),
            "dataset_rows": sum(m["row_counts"].values()),
            "ground_truth_rows": m["ground_truth_rows"],
            "findings_rows": m["findings_rows"],
            "verify_export": {name: c.ok for name, c in report.checks.items()},
        }
        self.timings["export_and_verify_seconds"] = round(time.monotonic() - t0, 1)
        if not report.ok:
            raise StageFailed("verify_export failed:\n" + "\n".join(report.lines()))
        self.say(f"  exported {len(m['files'])} files, combined_sha256={m['combined_sha256']}")
        self.say(f"  verify_export: {len(report.checks)} checks PASS")

