def run_child(*, out, seed, scale, scale_factor, config, log) -> None:
    """Runs inside the isolated subprocess. Writes results, transcript and report to ``out``."""
    from unittest import mock

    from django.contrib.auth import get_user_model
    from django.core.management import call_command
    from rest_framework.authtoken.models import Token
    from rest_framework.test import APIClient

    assert_isolated()
    out = Path(out)
    child = Child(out, seed, scale, scale_factor, config, log)
    status = {s: "NOT RUN" for s in STAGES}
    api = None
    error = None
    try:
        child.say("A  dataset: migrate, generate, inject, reconcile")
        child.stage_dataset()
        status["A_dataset"] = "PASS"
        child.say("B  export: CSV / JSON / SQL, ground truth, manifests; verify_export")
        child.stage_export()
        status["B_export"] = "PASS"

        call_command("seed_roles", stdout=io.StringIO())  # groups only; no demo users
        user = get_user_model().objects.create_user("demo_platform_admin")
        user.groups.add(
            *__import__("django.contrib.auth.models", fromlist=["Group"]).Group.objects.filter(
                name="platform_admin"
            )
        )
        client = APIClient()
        client.credentials(HTTP_AUTHORIZATION=f"Token {Token.objects.create(user=user).key}")
        api = Api(client)
        import logging

        logging.getLogger("django.request").setLevel(logging.ERROR)  # expected 4xx are recorded
        with (
            mock.patch("students.views.business_today", lambda: BUSINESS_DATE),
            mock.patch("academics.views.business_today", lambda: BUSINESS_DATE),
        ):
            child.say("C  anomalies of the generated dataset, with their ground-truth labels")
            child.stage_anomalies(api)
            status["C_anomalies"] = "PASS"
            child.say("D  evaluation against the ground truth")
            child.stage_evaluation(api)
            status["D_evaluation"] = "PASS"
            child.say("E  API workflow (ARCHITECTURE §9.3 and exception paths)")
            child.stage_api(api)
            status["E_api"] = "PASS"
            child.say("F  every remaining API operation (reads, writes, refusals)")
            child.stage_reference(api)
            status["F_reference"] = "PASS"
        child.say("G  permission probe: every operation x every role")
        child.stage_permissions()
        status["G_permissions"] = "PASS"
    except Exception as exc:  # recorded, reported, and re-raised as a non-zero exit
        failed = next(s for s in STAGES if status[s] == "NOT RUN")
        status[failed] = "FAIL"
        error = f"{type(exc).__name__}: {exc}"
    child.results["stages"] = status
    child.results["error"] = error
    child.results["parameters"] = {
        "seed": seed,
        "scale": scale_factor and f"factor {scale_factor}" or (scale or "starter"),
        "config": config or "config/generation.yaml",
        "business_date": BUSINESS_DATE.isoformat(),
    }
    transcript = api.calls if api else []
    (out / "api_transcript.json").write_text(
        json.dumps(
            {"masked_keys": sorted(VOLATILE_KEYS), "mask": VOLATILE, "calls": transcript},
            indent=2,
            sort_keys=True,
            ensure_ascii=False,
        )
        + "\n",
        encoding="utf-8",
    )
    child.results["api_calls"] = len(transcript)
    child.results["api_refusals"] = sum(1 for c in transcript if c["expected_status"] >= 400)
    (out / "demo_results.json").write_text(
        json.dumps(child.results, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (out / "demo_report.md").write_text(render_report(child.results, transcript), encoding="utf-8")
    (out / "logs").mkdir(exist_ok=True)
    (out / "logs/timings.json").write_text(json.dumps(child.timings, sort_keys=True) + "\n")
    if error:
        raise DemoError(error)


